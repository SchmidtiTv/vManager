    #[test]
    fn rendered_script_runs_the_hook_before_the_exe_and_propagates_failure() {
        let script = render_script("node.exe", Some(Path::new(r"C:\hooks\setup.ps1")));

        assert!(is_generated(&script));
        assert_eq!(parse_exe_marker(&script).as_deref(), Some("node.exe"));

        let hook_pos = script.find("& $Hook").unwrap();
        let exe_pos = script.find("& $Exe").unwrap();
        assert!(hook_pos < exe_pos, "the hook must run before the exe");

        // A failing hook must exit non-zero without ever reaching `& $Exe`.
        let abort_pos = script.find("exit $LASTEXITCODE\n}").unwrap_or_else(|| {
            script
                .find("exit 1")
                .expect("a failed hook aborts explicitly")
        });
        assert!(
            abort_pos < exe_pos,
            "abort-on-hook-failure must precede the exe launch"
        );
    }

