    #[test]
    fn repatch_updates_an_existing_shim_without_rediscovering() {
        let dir = tempfile::tempdir().unwrap();
        let root = tool(dir.path(), "1.0", &["node.exe"], Some("1.0"));
        write_shims(&root, &HashMap::new()).unwrap();

        // Remove the exe entirely: repatch must still succeed, because it
        // reuses the relative path already recorded in the file instead of
        // re-walking the (now exe-less) active version.
        std::fs::remove_file(root.join(link::LINK_NAME).join("node.exe")).unwrap();

        let hook = Path::new(r"C:\hooks\node.ps1");
        let result = repatch_hook(&root, "node", Some(hook)).unwrap();
        assert!(matches!(result, Repatch::Updated { .. }));

        let content = std::fs::read_to_string(root.join(SHIM_DIR_NAME).join("node.ps1")).unwrap();
        assert!(content.contains(r"C:\hooks\node.ps1"));
        assert_eq!(parse_exe_marker(&content).as_deref(), Some("node.exe"));

        let cleared = repatch_hook(&root, "node", None).unwrap();
        assert!(matches!(cleared, Repatch::Updated { .. }));
        let content = std::fs::read_to_string(root.join(SHIM_DIR_NAME).join("node.ps1")).unwrap();
        assert!(!content.contains("$Hook"));
    }

